#!/usr/bin/env python3
"""Evaluate the agent on the REAL open-data store and write EVALS_REAL.md from the measured results.

    python evals/run_real_evals.py           # run by ./run_demo.sh --real --evals, or after it with the same env

Runs every case in data/agricredit_real.db through the real LangGraph agent and MCP servers, on a throwaway copy
of the store, and checks properties that matter on real data: every advisory cites each public source, the
decision follows the capacity rules, seasonal price falls are flagged, conclusions agree with the computed key
findings, and a repeat run reproduces the same recommendation hash. Nothing in EVALS_REAL.md is written by hand.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "evals" / ".work_real"
sys.path.insert(0, str(ROOT / "src"))

src_db = Path(os.environ.get("AGRICREDIT_DB_PATH", ROOT / "data" / "agricredit_real.db"))
if not src_db.is_absolute():
    src_db = ROOT / src_db
if not src_db.exists():
    sys.exit("data/agricredit_real.db not found: run ./run_demo.sh --real first.")
if WORK.exists():
    shutil.rmtree(WORK)
(WORK / "fs_root").mkdir(parents=True)
shutil.copy(src_db, WORK / "real.db")
shutil.copytree(ROOT / "fs_mcp_root" / "policy", WORK / "fs_root" / "policy")
os.environ.update({"AGRICREDIT_DB_PATH": str(WORK / "real.db"), "AGRICREDIT_LOG_DIR": str(WORK / "logs"),
                   "AGRICREDIT_FS_MCP_ROOT": str(WORK / "fs_root"), "AGRICREDIT_FAULTS": ""})
os.environ.setdefault("AGRICREDIT_POLICY_FILE", "agent_policy_real.json")

from agricredit.agent.graph import key_findings, unsupported_claims  # noqa: E402
from agricredit.agent.runner import AgentRunner  # noqa: E402
from agricredit.config import AS_OF, get_settings  # noqa: E402
from agricredit.db import list_cases  # noqa: E402

SOURCES = {"ERA5 rainfall": "archive-api.open-meteo.com", "NASA POWER cross-check": "power.larc.nasa.gov",
           "WFP prices": "data.humdata.org", "Official commune yields": "HarvestStat"}


def check(st: dict) -> dict:
    a, asm, m = st.get("advisory") or {}, st.get("assessment") or {}, st.get("market") or {}
    out = {"case_id": st["case_id"], "status": st["status"], "recommendation": a.get("recommendation")}
    if not a:
        return out
    uris = " ".join(e["source_uri"] for e in a["evidence"])
    out["sources_cited"] = {k: v in uris for k, v in SOURCES.items()}
    base = a.get("base_repayment_capacity_ratio")
    out["rule_ok"] = not (a["recommendation"] == "RECOMMEND" and (base is None or base < 1.2)) and \
        not (a["recommendation"] in ("RECOMMEND", "RECOMMEND_WITH_CONDITIONS", "REDUCE_CREDIT_AMOUNT") and asm == {})
    seas = m.get("seasonal_anomaly_pct")
    flagged = any("usual" in w and "price" in w for w in a["data_quality_warnings"])
    out["seasonal_flag_ok"] = (seas is None) or ((seas <= -10) == flagged)
    out["claims"] = unsupported_claims(a["narrative"], key_findings(st)) if st.get("household") else []
    out["narrative_author"] = a["narrative_author"]
    out["timing"] = bool(asm.get("repayment_timing"))
    out["hash"] = a["recommendation_hash"]
    return out


def main() -> None:
    s = get_settings()
    runner = AgentRunner()
    cases = [c["case_id"] for c in list_cases()]
    t0 = time.time()
    results = [check(runner.start(cid)) for cid in cases]
    repeat = check(runner.start(cases[0]))
    elapsed = time.time() - t0
    drafted = [r for r in results if r.get("recommendation")]
    rec = Counter(r["recommendation"] for r in drafted)
    cover = {k: sum(r["sources_cited"][k] for r in drafted) for k in SOURCES}
    metrics = {
        "cases": len(results), "drafted": len(drafted),
        "rule_violations": sum(not r["rule_ok"] for r in drafted),
        "seasonal_flag_errors": sum(not r["seasonal_flag_ok"] for r in drafted),
        "narratives_contradicting_findings": sum(bool(r["claims"]) for r in drafted),
        "llm_narratives_kept": (sum(not r["narrative_author"].startswith("template") for r in drafted)
                                if s.is_open_weight_backend else "n/a (offline stub, no language model)"),
        "repayment_timing_computed": sum(r["timing"] for r in drafted),
        "reproducible": repeat.get("hash") == results[0].get("hash"),
        "recommendations": dict(rec), "source_coverage": cover, "elapsed_s": round(elapsed, 1),
    }
    (ROOT / "evals" / "results_real.json").write_text(json.dumps({"metrics": metrics, "cases": results}, indent=2, default=str))

    lines = ["# Evaluation on real open data", "",
             f"Generated by `evals/run_real_evals.py` on {dt.datetime.now():%Y-%m-%d %H:%M}, data as of {AS_OF:%Y-%m-%d %H:%M}, "
             f"model `{s.model_version}`, explanation language `{s.advisory_language}`. Households are simulated inside real "
             "communes; rainfall, prices, commune yields and input costs are real (see data/real/SOURCES.md).", "",
             "| Check | Result |", "|---|---|",
             f"| Cases run / advisories drafted | {metrics['cases']} / {metrics['drafted']} |"]
    for k, n in cover.items():
        lines.append(f"| Advisories citing {k} | {n} / {metrics['drafted']} |")
    lines += [f"| Recommendations that break the capacity rules | {metrics['rule_violations']} |",
              f"| Seasonal price falls (>= 10% below the usual month) not flagged, or flagged wrongly | {metrics['seasonal_flag_errors']} |",
              f"| Final explanations contradicting the computed key findings | {metrics['narratives_contradicting_findings']} |",
              f"| Model-written explanations kept (others fell back to the template) | {metrics['llm_narratives_kept']}"
              f"{' / ' + str(metrics['drafted']) if s.is_open_weight_backend else ''} |",
              f"| Cases with a repayment-timing scenario | {metrics['repayment_timing_computed']} |",
              f"| Repeat run reproduces the recommendation hash | {'yes' if metrics['reproducible'] else 'NO'} |",
              f"| Wall time | {metrics['elapsed_s']:.0f} s |", "",
              "Recommendations: " + ", ".join(f"{k} {v}" for k, v in sorted(rec.items())), "",
              "| Case | Recommendation | Explanation by | Sources cited |", "|---|---|---|---|"]
    for r in drafted:
        lines.append(f"| {r['case_id']} | {r['recommendation']} | {r['narrative_author'][:40]} | "
                     f"{sum(r['sources_cited'].values())}/{len(SOURCES)} |")
    (ROOT / "EVALS_REAL.md").write_text("\n".join(lines) + "\n")
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()
